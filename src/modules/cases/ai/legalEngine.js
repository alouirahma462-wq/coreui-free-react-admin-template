import { ai } from "./client.js"

export const legalEngine = async (caseText, articles) => {

  // 🧠 تجهيز السياق القانوني (RAG context)
  const context = articles
    .map(a => a.text)
    .join("\n\n====================\n\n")

  const prompt = `
أنت قاضٍ تونسي خبير في القانون الجزائي التونسي ومحلل قضائي عالي المستوى.

تعمل كمساعد قاضي/نيابة تحقيق.

⚠️ قواعد إلزامية:
- اعتمد فقط على النصوص القانونية المقدمة.
- لا تخترع مواد قانونية.
- لا تقدم إجابات مختصرة.
- حلل الوقائع بشكل قضائي احترافي عميق.
- استخرج النية الإجرامية بدقة.
- اربط الوقائع بالنص القانوني حرفياً.
- قيّم الأدلة بمنطق قضائي (حجية + قوة + تأثير).
- ناقش وجود الشك المعقول.
- استخدم reasoning قانوني تحليلي وليس سردي فقط.
- يجب أن يكون الرد تقريراً قضائياً رسمياً مفصلاً جداً.

🧾 القضية:
${caseText}

📚 النصوص القانونية (RAG CONTEXT):
${context}

⚖️ المطلوب:
أصدر تقريراً قضائياً مفصلاً جداً وفق الهيكل التالي:

────────────────────────────

# 🧾 أولاً: تلخيص الوقائع
- إعادة بناء الوقائع بطريقة قضائية
- ترتيب زمني للأحداث
- تحديد الفعل الجرمي الأساسي
- تحليل سلوك الأطراف

# 👥 ثانياً: الأطراف
- الضحية
- المتهم
- الشهود
- أطراف أخرى إن وجدت

# 🧠 ثالثاً: التحليل الواقعي
- ماذا حدث فعلاً؟
- ما هو الفعل الجرمي؟
- ما هي الوسائل المستخدمة؟
- هل توجد نية جنائية؟
- العلاقة السببية بين الفعل والنتيجة

# ⚖️ رابعاً: التحليل القانوني للأركان
## الركن المادي
- وصف قانوني دقيق
- ربط مباشر بالوقائع

## الركن المعنوي
- القصد الجنائي
- هل هو قصد مباشر أم احتمالي؟
- كيف تم استخلاص النية؟

## الظروف المشددة
- تحليل كل ظرف مشدد
- تأثيره القانوني

## الظروف المخففة
- وجودها من عدمه
- أثرها

# 📚 خامساً: التكييف القانوني
- تحديد الجريمة الأساسية
- الجرائم المرتبطة
- سبب الاختيار القانوني

# 📄 سادساً: الفصل القانوني
- ذكر الفصل كما ورد في النصوص القانونية

# 📜 سابعاً: نص المادة القانونية
- نسخ حرفي للنص القانوني

# 🔍 ثامناً: تحليل انطباق القانون
- تحليل كل عنصر في النص
- مقارنة النص بالوقائع

# 🧠 تاسعاً: التعليل القضائي
- reasoning قانوني مفصل جداً
- تحليل منطقي خطوة خطوة
- مناقشة عناصر الجريمة
- تقييم الأدلة وربطها بالقانون

# 🔎 عاشراً: تقييم الأدلة
لكل دليل:
- نوعه
- قوته
- حجّيته
- تأثيره على الإدانة

# ⚠️ حادي عشر: التناقضات والشكوك
- هل يوجد تناقض؟
- هل يوجد شك معقول؟
- أثره على الحكم

# 📊 ثاني عشر: نسبة الإدانة
- نسبة مئوية
- تبرير قانوني دقيق

# ⚖️ ثالث عشر: اقتراح العقوبة
- العقوبة الأصلية
- العقوبة المشددة
- العقوبة المخففة

# 🧾 أخيراً: الخلاصة القضائية
- النتيجة النهائية
- مدى ثبوت الجريمة
- الرأي القضائي النهائي
  `

  // 🤖 الاتصال بـ Ollama المحلي
  const res = await fetch("http://127.0.0.1:11434/api/generate", {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      model: "llama3.2:1b",
      prompt,
      stream: false
    })
  })

  const data = await res.json()

  return data?.response || "No response from Ollama"
}
