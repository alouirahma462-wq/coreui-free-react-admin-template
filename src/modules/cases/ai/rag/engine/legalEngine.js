import { openai } from "../client.js"

export const legalEngine = async (caseText, articles) => {

  const context = articles.map(a => a.text).join("\n\n====================\n\n")

  const res = await openai.chat.completions.create({
    model: "gpt-4o-mini",

    temperature: 0.2,

    messages: [
      {
        role: "system",
        content: `
أنت قاضٍ تونسي خبير في القانون الجزائي التونسي ومختص في التحليل الجنائي والقضائي.

تعتمد فقط على النصوص القانونية المقدمة لك.

مهمتك:
تحليل القضية تحليلاً قضائياً معمقاً ومفصلاً كما لو أنك تعد تقريراً قضائياً رسمياً أو مشروع حكم.

⚠️ تعليمات إلزامية:

- استخدم أسلوب قانوني احترافي رسمي.
- لا تختصر.
- لا تقدم إجابات سطحية.
- حلل الوقائع خطوة بخطوة.
- اربط كل عنصر من عناصر الجريمة بالنص القانوني المناسب.
- استخرج النية الإجرامية من الوقائع.
- حلل الركن المادي والمعنوي والظروف المشددة والمخففة.
- قيّم قوة الأدلة بشكل منفصل.
- حلل التناقضات المحتملة.
- قدّم reasoning قانوني حقيقي.
- عند عدم كفاية الأدلة وضّح ذلك قانونياً.
- اعتمد فقط على القانون التونسي.
- اذكر الفصل كما ورد حرفياً.
- اذكر نص المادة كما ورد حرفياً من النصوص القانونية المتوفرة.
- يجب أن يكون التحليل طويل ومفصل جداً.

يجب أن يكون التقرير شبيهاً بتقارير النيابة أو التحقيق أو الأحكام القضائية التحليلية.
        `
      },

      {
        role: "user",
        content: `
القضية:

${caseText}

النصوص القانونية المستخرجة:

${context}

أعطني تقريراً قانونياً مفصلاً جداً وفق الهيكل التالي:

# 🧾 تلخيص الوقائع
- إعادة بناء الوقائع بشكل قانوني ومنهجي وتحليلي
- ترتيب الأحداث زمنياً
- توضيح كيفية وقوع الجريمة
- تحليل سلوك الأطراف

# 👥 تحديد الأطراف
- الضحية
- المشتكى به / المتهم
- الشهود
- أي أطراف أخرى

# 🧠 التحليل الواقعي
- تحليل الوقائع
- استخراج الأفعال الجرمية
- تحديد الوسائل المستخدمة
- تحليل نية الجاني
- تحليل العلاقة السببية

# ⚖️ الأركان القانونية للجريمة
## الركن المادي
- شرح تفصيلي
- ربطه بالوقائع

## الركن المعنوي
- تحليل القصد الجنائي
- هل يوجد قصد مباشر أو غير مباشر
- كيف تم استنتاج النية

## الظروف المشددة
- تحليل كل ظرف مشدد
- مدى تأثيره على العقوبة

## الظروف المخففة
- هل توجد ظروف تخفيف
- تفسير ذلك قانونياً

# 📚 التكييف القانوني
- تحديد الجريمة الرئيسية
- تحديد الجرائم المتلازمة إن وجدت
- شرح سبب اختيار هذا التكييف

# 📄 الفصل القانوني
- ذكر الفصل أو المادة كما ورد حرفياً

# 📜 نص المادة القانونية
- نقل النص القانوني الحرفي كاملاً من النصوص القانونية المتوفرة

# 🔍 تحليل انطباق النص القانوني
- كيف تنطبق كل عبارة من المادة على الوقائع
- تحليل قانوني تفصيلي جداً

# 🧠 التعليل القانوني المفصل
- تعليل قضائي طويل ومفصل
- reasoning قانوني احترافي
- تحليل الأدلة والوقائع والقصد الجنائي
- مناقشة جميع العناصر القانونية

# 🔎 تحليل الأدلة
لكل دليل:
- نوع الدليل
- قوته
- مدى حجيته
- تأثيره على الإدانة

حلل:
- الشهادات
- الكاميرات
- الاعترافات
- التقارير الطبية
- القرائن

# ⚠️ تحليل التناقضات
- هل توجد تناقضات؟
- هل تؤثر على سلامة التتبع؟
- هل تخلق شكاً معقولاً؟

# 📊 تقييم نسبة الإدانة
- أعط نسبة مئوية
- برر النسبة قانونياً ومنطقياً بالتفصيل

# ⚖️ اقتراح العقوبة
## العقوبة الأصلية
## العقوبة المشددة
## العقوبة المخففة

مع تفسير قانوني لكل احتمال.

# 🧾 الخلاصة القضائية النهائية
- النتيجة النهائية
- الرأي القانوني النهائي
- مدى ثبوت الجريمة
        `
      }
    ]
  })

  return res.choices[0].message.content
}
